test('the old shop steps never change: a change to the shops’ tables is a new step at the end', () => {
  const now = MIGRATIONS.map(([name, sql]) => [name, createHash('sha256').update(sql).digest('hex').slice(0, 12)] as const);
  assert.deepEqual(now.slice(0, DONE.length).map(([name]) => name), DONE.map(([name]) => name), 'the steps keep their names and their order');
  for (const [i, [name, hash]] of DONE.entries())
    assert.equal(now[i][1], hash, `${name} was changed: put the change in a new step at the end (migrations/1xx_…): a server that did ${name} never runs it again`);
  assert.equal(now.length, DONE.length, 'a new step: add its line to DONE once it is written');
  assert.equal(new Set(now.map(([name]) => name)).size, now.length, 'two steps with the same name: the second would never run');
});
